"""Cross-platform task runner (the Makefile calls this; on Windows without make, run `python tasks.py <target>`).

  secrets  write .env with fresh secrets           up      API :8010 + console :5180 (background)
  seed     load demo data (+ sample files)          demo    up + seed + print the demo URLs
  test     unit/integration tests                   e2e     Playwright acceptance tests (needs `up`)
  eval     evaluation report -> docs/EVAL.md        probe   GPU/model probe -> docs/VERSIONS.md
  eval-real  score real files in realdata/ against realdata/truth.csv (offline)
  worker   local AI worker: runs agents on this GPU for the hosted site (needs .env.worker with MONGODB_URI)
  fetch-public / eval-public  public dataset subsets (MIT Indoor 67, CubiCasa5K, IIIT-HW-Dev) and their scores
  down     stop servers started by `up`             cron    run nightly jobs once
Use MODE=FULL (env or .env) for GPU models; default is LITE."""
import base64
import json
import os
import secrets
import subprocess
import sys
import time
import urllib.request

ROOT = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable
PIDS = os.path.join(ROOT, ".pids.json")


def load_env():
    p = os.path.join(ROOT, ".env")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.strip().split("=", 1)
                os.environ.setdefault(k, v.strip('"'))


def sh(cmd, **kw):
    print("+", " ".join(cmd))
    return subprocess.call(cmd, cwd=ROOT, **kw)


def http(method, url, headers=None, body=None, timeout=120):
    req = urllib.request.Request(url, method=method, headers=headers or {}, data=body)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read() or b"null")


def secrets_():
    p = os.path.join(ROOT, ".env")
    if os.path.exists(p):
        print(".env exists; leaving it alone")
        return
    vals = {"MODE": "LITE", "SESSION_SECRET": secrets.token_urlsafe(32), "FIELD_KEY": base64.b64encode(os.urandom(32)).decode(),
            "SEED_TOKEN": secrets.token_urlsafe(18), "DEMO_PASSWORD": "pramaan-" + secrets.token_urlsafe(6), "DEMO": "true", "MAX_UPLOAD_MB": "25"}
    open(p, "w", encoding="utf-8").write("# Generated by tasks.py secrets. Never commit.\n" + "".join(f"{k}={v}\n" for k, v in vals.items()))
    print("wrote .env (demo password:", vals["DEMO_PASSWORD"] + ")")


def up():
    load_env()
    os.environ.setdefault("PUBLIC_URL", "http://127.0.0.1:8010")
    log = open(os.path.join(ROOT, "server.log"), "w")
    api = subprocess.Popen([PY, "-m", "uvicorn", "pramaan.main:app", "--port", "8010"], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
    npm = "npm.cmd" if os.name == "nt" else "npm"
    web = subprocess.Popen([npm, "run", "dev", "--", "--port", "5180", "--strictPort"], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
    json.dump({"api": api.pid, "web": web.pid}, open(PIDS, "w"))
    for _ in range(120):
        try:
            h = http("GET", "http://127.0.0.1:8010/api/health", timeout=3)
            print("API up:", h["mode"], "store:", h["store"])
            break
        except Exception:
            time.sleep(1)
    print("Console: http://localhost:5180   Host A: http://localhost:5180/host-a/   Host B: http://localhost:5180/host-b/")


def down():
    if not os.path.exists(PIDS):
        return
    for name, pid in json.load(open(PIDS)).items():
        if os.name == "nt":
            subprocess.call(["taskkill", "/F", "/T", "/PID", str(pid)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        else:
            try:
                os.kill(pid, 15)
            except OSError:
                pass
        print("stopped", name)
    os.remove(PIDS)


def seed():
    """With MONGODB_URI: seed directly. Without: ask the running in-memory server to reseed itself."""
    load_env()
    sh([PY, "-m", "pramaan.seed", "--samples", "public/samples"]) if os.environ.get("MONGODB_URI") else None
    if not os.environ.get("MONGODB_URI"):
        tok = {"X-Seed-Token": os.environ.get("SEED_TOKEN", "")}
        print(http("POST", "http://127.0.0.1:8010/api/admin/seed", tok))
        while not http("POST", "http://127.0.0.1:8010/api/admin/seed-next", tok, timeout=600).get("done"):
            pass
        print("seeded in-memory store")


def demo():
    up()
    seed()
    print("\nDemo ready. Open http://localhost:5180 and pick 'Enter as Senior Officer'. Script: docs/DEMO.md")


def test():
    sys.exit(sh([PY, "-m", "pytest", "-q", "-p", "no:cacheprovider", "tests"]))


def e2e():
    sys.exit(sh([PY, "-m", "pytest", "-q", "-p", "no:cacheprovider", "e2e"]))


def eval_():
    load_env()
    sys.exit(sh([PY, "-m", "pramaan.evaluate", "--report", "docs/EVAL.md"]))


def eval_real():
    """Scores PRAMAAN on real, permitted files in realdata/ (offline, nothing leaves this machine)."""
    load_env()
    sys.exit(sh([PY, "-m", "pramaan.evaluate_real"], env={k: v for k, v in os.environ.items() if k not in ("MONGODB_URI", "GROQ_KEY", "SMTP_HOST")}))


def fetch_public():
    """Downloads small research-use subsets of public datasets into realdata/public/ (gitignored)."""
    sys.exit(sh([PY, "scripts/fetch_public_data.py"] + sys.argv[2:]))


def eval_public():
    """Scores the models on those public datasets (offline). Use MODE=FULL."""
    sys.exit(sh([PY, "-m", "pramaan.evaluate_public"]))


def worker():
    """Local AI worker for the hosted site: reads .env.worker (MONGODB_URI of the live database), runs agents on this GPU."""
    p = os.path.join(ROOT, ".env.worker")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.strip().split("=", 1)
                os.environ[k] = v.strip('"')
    sys.exit(sh([PY, "-m", "pramaan.worker"] + sys.argv[2:]))


def probe():
    sys.exit(sh([PY, "scripts/gpu_probe.py", "--load"]))


def cron():
    load_env()
    tok = {"X-Seed-Token": os.environ.get("SEED_TOKEN", "")}
    print(http("GET", "http://127.0.0.1:8010/api/cron/daily", tok))


TARGETS = {"secrets": secrets_, "up": up, "down": down, "seed": seed, "demo": demo, "test": test, "e2e": e2e, "eval": eval_, "eval-real": eval_real, "fetch-public": fetch_public, "worker": worker, "eval-public": eval_public,
           "probe": probe, "cron": cron}

if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in TARGETS:
        print(__doc__)
        sys.exit(1)
    TARGETS[sys.argv[1]]()
